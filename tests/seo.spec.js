import { test, expect } from '@playwright/test'

test('metadata follows launch, navigation, products and language without leaking query strings', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-22T12:00:00+02:00'))
  await page.goto('/')
  await expect(page).toHaveTitle('Klaar voor de start? | Streetmasters')
  await page.goto('/dikkeseppe/diensten?discount=')
  await expect(page).toHaveTitle('Diensten Overzicht | Streetmasters')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'noindex,follow')
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'https://streetmasters.be/diensten')
  await page.clock.setFixedTime(new Date('2026-11-01T12:00:00+01:00'))
  await page.goto('/diensten')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'index,follow')
  await expect(page.locator('meta[name="description"]')).toHaveAttribute('content', /Van moleculaire/)
  await page.locator('nav a[href="/about"]').click()
  await expect(page).toHaveTitle('Wie Is Streetmasters? | Streetmasters')
  await page.goto('/shop/nos-autogeur-blauw')
  const title = await page.locator('main h1').textContent()
  await expect(page).toHaveTitle(`${title} | Streetmasters`)
  await page.evaluate(() => localStorage.setItem('streetmasters-locale', 'en'))
  await page.goto('/about')
  await expect(page).toHaveTitle('Who Is Streetmasters? | Streetmasters')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.goto('/winkelmand')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'noindex,follow')
})
